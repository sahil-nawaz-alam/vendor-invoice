import streamlit as st
import pandas as pd
import numpy as np
import joblib
from pathlib import Path

st.set_page_config(page_title="Vendor Invoice Intelligence", page_icon="📊", layout="wide")

MODEL_DIR = Path(__file__).parent / "models"
FREIGHT_MODEL_PATH = MODEL_DIR / "predict_freight_model.pkl"
FLAG_MODEL_PATH = MODEL_DIR / "predict_flag_invoice_model.pkl"
SCALER_PATH = MODEL_DIR / "scaler.pkl"

st.title("📊 Vendor Invoice Intelligence System")
st.caption("Freight cost prediction • Invoice risk flagging")

@st.cache_resource
def load_models():
    missing = [str(p.name) for p in [FREIGHT_MODEL_PATH, FLAG_MODEL_PATH, SCALER_PATH] if not p.exists()]
    if missing:
        return None, None, None, missing
    return (joblib.load(FREIGHT_MODEL_PATH), joblib.load(FLAG_MODEL_PATH),
            joblib.load(SCALER_PATH), [])

freight_model, flag_model, scaler, missing = load_models()

if missing:
    st.error("Model files not found: " + ", ".join(missing))
    st.info("Train the models in your notebook and place the three .pkl files in a `models/` folder beside app.py.")
    st.stop()

tab1, tab2, tab3 = st.tabs(["🚚 Freight Prediction", "🚩 Invoice Risk Check", "ℹ️ About"])

with tab1:
    st.subheader("Freight Cost Prediction")
    st.write("Estimate freight charges using the invoice dollar value.")
    dollars = st.number_input("Invoice / purchase dollar value", min_value=0.0, value=18500.0, step=100.0)
    if st.button("Predict Freight", key="predict_freight"):
        pred = float(freight_model.predict(pd.DataFrame({"Dollars": [dollars]}))[0])
        st.metric("Estimated Freight", f"{pred:,.2f}")
        st.caption("Estimate generated by the trained regression model.")

with tab2:
    st.subheader("Invoice Risk Flagging")
    st.write("Check invoice-level metrics for a risk flag. This model uses the five features from your notebook.")
    c1, c2 = st.columns(2)
    with c1:
        invoice_quantity = st.number_input("Invoice Quantity", min_value=0.0, value=50.0)
        invoice_dollars = st.number_input("Invoice Dollars", min_value=0.0, value=352.95, step=10.0)
        freight = st.number_input("Freight", min_value=0.0, value=1.73, step=0.1)
    with c2:
        total_item_quantity = st.number_input("Total Item Quantity", min_value=0.0, value=162.0)
        total_item_dollars = st.number_input("Total Item Dollars", min_value=0.0, value=2476.0, step=10.0)

    if st.button("Check Invoice Risk", key="check_risk"):
        features = pd.DataFrame([{
            "invoice_quantity": invoice_quantity,
            "invoice_dollars": invoice_dollars,
            "Freight": freight,
            "total_item_quantity": total_item_quantity,
            "total_item_dollars": total_item_dollars,
        }])
        scaled = scaler.transform(features)
        flag = int(flag_model.predict(scaled)[0])
        st.divider()
        if flag == 1:
            st.warning("🚩 Manual approval recommended — this invoice has been flagged by the model.")
        else:
            st.success("✅ No risk flag predicted — this invoice appears normal according to the model.")
        st.write("**Entered data**")
        st.dataframe(features, use_container_width=True)

with tab3:
    st.subheader("Project overview")
    st.markdown("""
    This app demonstrates two machine-learning workflows:

    - **Regression:** Predicts freight cost from `Dollars`.
    - **Classification:** Predicts an invoice risk/manual-review flag from invoice and aggregated purchase features.

    The classification model was trained using scaled features. The scaler saved with the model is used automatically for predictions.

    **Important:** This is a model-based screening aid, not a definitive fraud or accounting decision.
    """)
